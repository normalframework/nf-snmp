def system_truth():
    """System scalars snmpd itself serves from the generated config."""
    return [
        ("1.3.6.1.2.1.1.1.0", "sysDescr.0", "OctetString", model.sysDescr),
        ("1.3.6.1.2.1.1.2.0", "sysObjectID.0", "OID", model.sysObjectID),
        ("1.3.6.1.2.1.1.5.0", "sysName.0", "OctetString", model.sysName or MODEL_KEY),
    ]


def truth(at_ms):
    step = at_ms // STEP_MS
    rows, eng = model.snapshot(step)
    raw = {}
    for oid, name, typ, v in system_truth():
        raw[oid] = {"type": typ, "value": norm_value(typ, v)}
        eng[name] = {"value": v}
    for _k, oid, typ, val in rows:
        raw[oid] = {"type": typ, "value": val}
    return {"at": at_ms, "step": step, "stepMs": STEP_MS, "raw": raw, "eng": eng}


def info():
    step = int(time.time() * 1000) // STEP_MS
    rows, _ = model.snapshot(step)
    wobjs = model.writable_objects()
    writable = [oid for _k, oid, _t, _v in rows
                if any(oid.startswith(o.oid + ".") for o in wobjs)]
    return {
        "model": model.name,
        "simModel": MODEL_KEY,
        "sysObjectID": model.sysObjectID,
        "sysDescr": model.sysDescr,
        "stepMs": STEP_MS,
        "engineID": engine_id(),
        "communities": {"public": "ro", "private": "rw"},
        "users": [{"user": u[0], "authProtocol": u[3], "privProtocol": u[4],
                   "level": level_of(u), "access": "ro" if u[0] == "noauth" else "rw"}
                  for u in ACTIVE_USERS],
        "authKey": AUTH_PASS,
        "privKey": PRIV_PASS,
        "writable": writable,
        "roots": list(model.pass_roots),
        "trapOID": model.trap_oid,
    }


TRAP_TYPE_FLAG = {"Integer": "i", "Gauge32": "u", "Counter32": "c", "Counter64": "C",
                  "TimeTicks": "t", "IpAddress": "a", "OID": "o", "OctetString": "s"}


def v1_mapping(trap_oid):
    """RFC 3584 §3.2 reverse mapping: (enterprise, generic, specific)."""
    std = "1.3.6.1.6.3.1.1.5."
    if trap_oid.startswith(std):
        return model.sysObjectID, int(trap_oid[len(std):]) - 1, 0
    parts = trap_oid.split(".")
    if parts[-2] == "0":
        return ".".join(parts[:-2]), 6, int(parts[-1])
    return ".".join(parts[:-1]), 6, int(parts[-1])


def send_trap(req):
    target = req.get("target")
    if not target:
        raise ValueError("target required (host:port)")
    version = str(req.get("version", "2c"))
    inform = bool(req.get("inform", False))
    step = int(time.time() * 1000) // STEP_MS
    vbs = model.trap_varbinds(step)
    trap_oid = model.trap_oid
    if inform and version == "1":
        raise ValueError("SNMPv1 has no inform")
    tool = "snmpinform" if inform else "snmptrap"
    args = [tool, "-On", "-r", str(int(req.get("retries", 1))),
            "-t", str(float(req.get("timeoutMs", 2000)) / 1000.0)]
    if version in ("1", "2c"):
        args += ["-v", version, "-c", req.get("community", "public")]
    elif version == "3":
        uname = req.get("user", "shaaes")
        u = next((x for x in ACTIVE_USERS if x[0] == uname), None)
        if u is None:
            raise ValueError("unknown v3 user %r" % uname)
        args += ["-v", "3", "-u", uname, "-l", level_of(u)]
        if u[1]:
            args += ["-a", u[1], "-A", AUTH_PASS]
        if u[2]:
            args += ["-x", u[2], "-X", PRIV_PASS]
        if not inform:
            args += ["-e", "0x" + engine_id()]
    else:
        raise ValueError("bad version %r" % version)
    host = target
    if not host.startswith(("udp:", "tcp:", "udp6:")):
        host = "udp:" + host
    args.append(host)
    if version == "1":
        ent, gen, spec = v1_mapping(trap_oid)
        args += ["." + ent, "", str(gen), str(spec), ""]
    else:
        args += ["", "." + trap_oid]
    out_vbs = []
    for oid, typ, raw in vbs:
        val = norm_value(typ, raw)
        flag = TRAP_TYPE_FLAG[typ]
        if typ == "OctetString":
            text = raw if isinstance(raw, str) else bytes(raw).decode("latin-1")
            args += ["." + oid, "s", text]
        elif typ == "OID":
            args += ["." + oid, "o", "." + val]
        else:
            args += ["." + oid, flag, val]
        out_vbs.append({"oid": oid, "type": typ, "value": val})
    p = subprocess.run(args, capture_output=True, text=True, timeout=30)
    return {"ok": p.returncode == 0, "rc": p.returncode, "stderr": p.stderr.strip(),
            "command": args[0], "version": version, "inform": inform,
            "trapOID": trap_oid, "varbinds": out_vbs,
            "v1": dict(zip(("enterprise", "generic", "specific"), v1_mapping(trap_oid)))
            if version == "1" else None}


class Handler(BaseHTTPRequestHandler):
    server_version = "nfsnmp-sim/1"

    def log_message(self, fmt, *args):
        if os.environ.get("SIM_HTTP_LOG"):
            log("http " + fmt % args)

    def reply(self, code, obj):
        body = json.dumps(obj, indent=None).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        if not n:
            return {}
        return json.loads(self.rfile.read(n) or b"{}")

    def do_GET(self):
        u = urlparse(self.path)
        q = parse_qs(u.query)
        try:
            if u.path == "/info":
                return self.reply(200, info())
            if u.path == "/truth":
                at = int(q["at"][0]) if "at" in q else int(time.time() * 1000)
                return self.reply(200, truth(at))
            if u.path in ("/", "/health"):
                return self.reply(200, {"ok": True, "model": model.name})
            return self.reply(404, {"error": "not found"})
        except Exception as e:  # pragma: no cover
            return self.reply(500, {"error": repr(e)})

    def do_POST(self):
        u = urlparse(self.path)
        try:
            if u.path == "/reset":
                state.reset()
                return self.reply(200, {"ok": True})
            if u.path == "/trap":
                r = send_trap(self.body())
                return self.reply(200 if r["ok"] else 502, r)
            if u.path == "/set-fault":
                return self.reply(400, {"error": "faults are only supported by sim-quirky"})
            return self.reply(404, {"error": "not found"})
        except ValueError as e:
            return self.reply(400, {"error": str(e)})
        except Exception as e:  # pragma: no cover
            return self.reply(500, {"error": repr(e)})


def main():
    os.makedirs(os.path.dirname(STATE_PATH), exist_ok=True)
    os.makedirs("/run/sim", exist_ok=True)
    if os.environ.get("SIM_RESET_ON_START", "1") == "1":
        state.reset()
    os.makedirs(os.path.dirname(CONF), exist_ok=True)
    with open(CONF, "w") as f:
        f.write(render_conf())
    # snmpd persists USM keys and engine boots here; start clean so the
    # createUser lines above are authoritative.
    for p in ("/var/lib/snmp/snmpd.conf",):
        try:
            os.unlink(p)
        except FileNotFoundError:
            pass
    if "--print-conf" in sys.argv:
        sys.stdout.write(render_conf())
        return
    snmpd = Snmpd()
    httpd = ThreadingHTTPServer(("0.0.0.0", HTTP_PORT), Handler)
    httpd.daemon_threads = True

    def shutdown(*_):
        snmpd.stop()
        threading.Thread(target=httpd.shutdown, daemon=True).start()

    signal.signal(signal.SIGTERM, shutdown)
    signal.signal(signal.SIGINT, shutdown)
    t = threading.Thread(target=snmpd.run, daemon=True)
    t.start()
    log("model=%s stepMs=%d users=%s http=:%d" % (
        MODEL_KEY, STEP_MS, ",".join(u[0] for u in ACTIVE_USERS), HTTP_PORT))
    httpd.serve_forever()
    snmpd.stop()


if __name__ == "__main__":
    main()
