"""Device simulator supervisor: renders snmpd.conf for SIM_MODEL, runs snmpd
(restarting it if it dies) and serves the ground-truth HTTP API on :8000.

HTTP API (docs/internals.md §2): GET /info, GET /truth?at=<unix_ms>,
POST /trap, POST /reset.
"""

import json
import os
import signal
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from simcore import StateStore, norm_value  # noqa: E402
from models import get_model  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_KEY = os.environ.get("SIM_MODEL", "apc-ups")
STEP_MS = int(os.environ.get("SIM_STEP_MS", "10000"))
STATE_PATH = os.environ.get("SIM_STATE", "/run/sim/state.json")
HTTP_PORT = int(os.environ.get("SIM_HTTP_PORT", "8000"))
SNMP_PORT = int(os.environ.get("SIM_SNMP_PORT", "161"))
CONF = "/etc/snmp/snmpd.conf"
AUTH_PASS = "authpass123"
PRIV_PASS = "privpass123"

# (user, net-snmp auth, net-snmp priv, §1 authProtocol, §1 privProtocol)
USERS = [
    ("noauth", None, None, "none", "none"),
    ("authsha", "SHA", None, "sha", "none"),
    ("md5des", "MD5", "DES", "md5", "des"),
    ("shaaes", "SHA", "AES", "sha", "aes"),
    ("sha256aes", "SHA-256", "AES", "sha256", "aes"),
    ("sha512aes", "SHA-512", "AES", "sha512", "aes"),
    ("sha256aes256", "SHA-256", "AES-256", "sha256", "aes256b"),
]

state = StateStore(STATE_PATH)
model = get_model(MODEL_KEY)(state, STEP_MS)


def log(msg):
    sys.stderr.write("simd[%s]: %s\n" % (MODEL_KEY, msg))
    sys.stderr.flush()


def blumenthal_supported():
    try:
        out = subprocess.run(["net-snmp-config", "--configure-options"],
                             capture_output=True, text=True, timeout=10).stdout
        return "--enable-blumenthal-aes" in out
    except (OSError, subprocess.SubprocessError):
        # net-snmp-config ships in libsnmp-dev; fall back to the snmpget help text
        p = subprocess.run(["snmpget", "-h"], capture_output=True, text=True)
        out = p.stdout + p.stderr
        return "AES-256" in out


def configured_users():
    users = []
    b = blumenthal_supported()
    for u in USERS:
        if u[2] == "AES-256" and not b:
            continue
        users.append(u)
    return users


ACTIVE_USERS = configured_users()


def engine_id():
    """Fixed per model: RFC 3411 format 4 (text), enterprise 8072 (net-snmp)."""
    return "80001f8804" + ("nfsnmp-" + MODEL_KEY).encode().hex()


def level_of(u):
    return "noAuthNoPriv" if not u[1] else ("authNoPriv" if not u[2] else "authPriv")


def render_conf():
    q = lambda s: '"%s"' % s.replace('"', "'")  # noqa: E731
    lines = [
        "# generated by simd.py for model %s" % MODEL_KEY,
        "agentAddress udp:%d" % SNMP_PORT,
        "exactEngineID 0x%s" % engine_id(),
        "sysObjectID .%s" % model.sysObjectID,
        "sysDescr %s" % model.sysDescr,
        "sysName %s" % (model.sysName or MODEL_KEY),
        "sysServices 72",
        "rocommunity public default",
        "rwcommunity private default",
        "master no",
        "dontLogTCPWrappersConnects yes",
        "trapcommunity public",
    ]
    for u in ACTIVE_USERS:
        name, a, p = u[0], u[1], u[2]
        if not a:
            lines.append("createUser %s" % name)
        elif not p:
            lines.append("createUser %s %s %s" % (name, a, AUTH_PASS))
        else:
            lines.append("createUser %s %s %s %s %s" % (name, a, AUTH_PASS, p, PRIV_PASS))
        lvl = {"noAuthNoPriv": "noauth", "authNoPriv": "auth", "authPriv": "priv"}[level_of(u)]
        lines.append("%s %s %s" % ("rouser" if name == "noauth" else "rwuser", name, lvl))
    py = "/usr/bin/python3"
    pp = os.path.join(HERE, "passpersist.py")
    # sysContact / sysLocation: served (writable, persisted) by the model with
    # a higher priority (lower number) than snmpd's own system_mib.
    for root in ["1.3.6.1.2.1.1.4", "1.3.6.1.2.1.1.6"] + list(model.pass_roots):
        lines.append("pass_persist -p 1 .%s %s %s .%s" % (root, py, pp, root))
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# snmpd supervision
# --------------------------------------------------------------------------

class Snmpd:
    def __init__(self):
        self.proc = None
        self.stopping = False

    def cmd(self):
        # -m "": load no MIB files (we only use numeric OIDs; avoids log noise)
        c = ["snmpd", "-f", "-Lo", "-C", "-c", CONF, "-m", "", "-p", "/run/sim/snmpd.pid"]
        if model.snmpd_exclude:
            c += ["-I", "-" + ",".join(model.snmpd_exclude)]
        return c

    def run(self):
        while not self.stopping:
            log("starting %s" % " ".join(self.cmd()))
            self.proc = subprocess.Popen(self.cmd(), env=dict(os.environ))
            rc = self.proc.wait()
            if self.stopping:
                return
            log("snmpd exited rc=%s; restarting in 1s" % rc)
            time.sleep(1)

    def stop(self):
        self.stopping = True
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()


